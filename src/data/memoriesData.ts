// Helper to extract Drive ID and get thumbnail
export function extractDriveId(url: string): string {
  const match = url.match(/\/d\/([a-zA-Z0-9_-]+)/);
  return match ? match[1] : '';
}

export function getDriveThumbnailUrl(driveId: string, size: number = 800): string {
  return `https://drive.google.com/thumbnail?id=${driveId}&sz=w${size}`;
}

export function getDriveDirectViewUrl(driveId: string): string {
  return `https://drive.google.com/file/d/${driveId}/view`;
}

